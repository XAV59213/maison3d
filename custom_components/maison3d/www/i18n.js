export {TEXT as UI_TEXT};

let lang="fr";
const subscribers=new Set();
export const uiLang=()=>lang;
export function setUiLang(value){
  if(!value)return;
  const next=langOf(value);
  if(next===lang)return;
  lang=next;for(const fn of subscribers){try{fn(lang)}catch(err){console.error(err)}}
}
export function onUiLang(fn){subscribers.add(fn);fn(lang);return()=>subscribers.delete(fn)}

/** t(lang, key, vars) or t(key, vars) using the current UI language. */
export function t(langOrKey,keyOrVars={},vars={}){
  const named=typeof keyOrVars==="string";
  const code=named?langOf(langOrKey):lang;
  const key=named?keyOrVars:langOrKey;
  const params=named?vars:keyOrVars;
  const text=TEXT[code]?.[key]??TEXT.fr[key]??key;
  return String(text).replace(/\{(\w+)\}/g,(_,k)=>params[k]??"");
}

/** Weather / season / image-slot label in the active language. */
export function labelOf(lang,key){
  return t(lang,"label_"+key);
}

