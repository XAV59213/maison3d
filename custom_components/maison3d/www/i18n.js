export const localeTag=()=>uiLang()==="fr"?"fr-FR":"en-GB";
export function formatTime(value,opts){
  try{return new Date(value).toLocaleTimeString(localeTag(),opts||{hour:"2-digit",minute:"2-digit"})}catch{return ""}
}
export function formatDateTime(value){
  try{return new Date(value).toLocaleString(localeTag(),{dateStyle:"short",timeStyle:"short"})}catch{return ""}
}
export function applyDocumentLang(){
  if(typeof document==="undefined")return;
  document.documentElement.lang=uiLang();
  for(const el of document.querySelectorAll("[data-i18n]")){
    const key=el.getAttribute("data-i18n");if(!key)continue;
    el.textContent=t(key);
  }
  for(const el of document.querySelectorAll("[data-i18n-title]")){
    const key=el.getAttribute("data-i18n-title");if(key)el.title=t(key);
  }
  for(const el of document.querySelectorAll("[data-i18n-aria]")){
    const key=el.getAttribute("data-i18n-aria");if(key)el.setAttribute("aria-label",t(key));
  }
}
